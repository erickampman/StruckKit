#!/usr/bin/env python3
"""Generate src/Module/PlateModesTable.hpp: the vibration modes of a thin circular plate with a
free edge (Kirchhoff theory), the starting point for StruckKit's cymbals.

For each mode W(r) cos(m theta), W = J_m(lam r) + C I_m(lam r) on the unit disc, the free-edge
conditions (zero bending moment and zero effective shear at r = 1) give a 2x2 determinant whose
roots are the eigenvalues lam. Frequency is proportional to lam^2. For each root this script
records:

    m, n     nodal diameters, nodal circles (Leissa's labelling: the first m = 0 and m = 1 roots
             are (0,1) and (1,1); rigid-body motions are excluded)
    lam      the eigenvalue
    c        C * I_m(lam), so the shape is J_m(lam r) + c * I_m(lam r) / I_m(lam) without overflow
    invNorm  1 / sqrt(modal mass), the modal mass being the integral of W^2 over the disc

Above the table StruckKit places the (thousands of) remaining modes by semiclassical (WKB)
quantisation: a mode (m, n) sits where the radial phase

    Phi_m(lam) = sqrt(lam^2 - m^2) - m arccos(m / lam)

equals pi (n + delta). The script fits delta as a quadratic in mu = m / lam over the exact roots with
lam > 15 and reports how well the fitted rule reproduces them (well under 1% in lam).

Checked against Leissa, "Vibration of Plates" (NASA SP-160), free circular plate, nu = 0.33:
lam^2 = 5.262 (2,0), 9.067 (0,1), 12.24 (3,0), 20.51 (1,1), 21.53 (4,0), ...

Usage: tools/gen_plate_modes.py > src/Module/PlateModesTable.hpp
"""

import numpy as np
from scipy.integrate import quad
from scipy.optimize import brentq
from scipy.special import iv, ivp, jv, jvp

NU = 0.33          # Poisson's ratio. Bronze is ~0.34; the low-mode ratios move < 1% across that.
LAM_MAX = 40.0     # tabulate every mode with lam below this (lam^2 < 1600)


def terms(x, m):
    J, Jp, Jpp = jv(m, x), jvp(m, x, 1), jvp(m, x, 2)
    I, Ip, Ipp = iv(m, x), ivp(m, x, 1), ivp(m, x, 2)
    MA = x * x * Jpp + NU * (x * Jp - m * m * J)            # bending moment, J part
    MB = x * x * Ipp + NU * (x * Ip - m * m * I)            # ... I part
    VA = -x**3 * Jp - (1 - NU) * m * m * (x * Jp - J)       # effective shear, J part
    VB = x**3 * Ip - (1 - NU) * m * m * (x * Ip - I)        # ... I part
    return MA, MB, VA, VB, I


def det(x, m):
    MA, MB, VA, VB, I = terms(x, m)
    return (MA * VB - MB * VA) / I                           # I column scaled to stay finite


def roots(m):
    xs = np.linspace(0.3, LAM_MAX, int(LAM_MAX * 200))
    v = [det(x, m) for x in xs]
    out = []
    for i in range(len(xs) - 1):
        if np.sign(v[i]) != np.sign(v[i + 1]):
            r = brentq(det, xs[i], xs[i + 1], args=(m,), xtol=1e-12)
            if abs(det(r, m)) < 1e-6 * (1 + abs(det(xs[i], m))):   # a root, not a pole
                out.append(r)
    return out


modes = []
for m in range(0, 80):
    rs = roots(m)
    if not rs:
        break
    for k, lam in enumerate(rs):
        n = k + 1 if m <= 1 else k
        MA, MB, VA, VB, I = terms(lam, m)
        C = -MA / MB                       # from the moment condition
        c_scaled = C * I
        shape = lambda r: jv(m, lam * r) + C * iv(m, lam * r)
        integral, _ = quad(lambda r: shape(r) ** 2 * r, 0.0, 1.0, limit=400)
        mass = integral * (2 * np.pi if m == 0 else np.pi)
        modes.append((lam, m, n, c_scaled, 1.0 / np.sqrt(mass)))
modes.sort()

# WKB offset fit. The radial index is n itself: index 0 of m = 0 and m = 1 is the rigid-body mode.
def phase(m, lam):
    return np.sqrt(lam * lam - m * m) - m * np.arccos(m / lam)

fit = [md for md in modes if md[0] > 15 and md[1] < md[0]]
mu = np.array([md[1] / md[0] for md in fit])
delta = np.array([phase(md[1], md[0]) / np.pi - md[2] for md in fit])
A = np.c_[np.ones_like(mu), mu, mu * mu]
d0, d1, d2 = np.linalg.lstsq(A, delta, rcond=None)[0]
# Phase error -> eigenvalue error: dPhi/dlam = sqrt(lam^2 - m^2) / lam.
lam_err = [(delta[i] - A[i] @ [d0, d1, d2]) * np.pi * fit[i][0] / np.sqrt(fit[i][0] ** 2 - fit[i][1] ** 2)
           for i in range(len(fit))]
rel = max(abs(e) / fit[i][0] for i, e in enumerate(lam_err))

print("// Generated by tools/gen_plate_modes.py — do not edit. See that script for the derivation.")
print("//")
print(f"// Free circular Kirchhoff plate, nu = {NU}: {len(modes)} modes with lam < {LAM_MAX:g}, sorted by")
print("// frequency (proportional to lam^2). Columns: m, n, lam, c = C * I_m(lam), 1/sqrt(modal mass).")
print(f"// WKB rule for modes above the table: Phi_m(lam) = pi (n + delta), delta = {d0:.5f} + {d1:.5f} mu + {d2:.5f} mu^2")
print(f"// (mu = m / lam); against the exact roots with lam > 15 its worst error in lam is {100 * rel:.2f}%.")
print()
print("#ifndef PlateModesTable_hpp")
print("#define PlateModesTable_hpp")
print()
print("struct PlateModeIndex { int m; int n; double lam; double c; double invNorm; };")
print()
print("static constexpr PlateModeIndex kPlateModes[] = {")
for lam, m, n, c, inv in modes:
    print(f"    {{ {m}, {n}, {lam:.6f}, {c:.9e}, {inv:.9e} }},")
print("};")
print("static constexpr int kPlateModeCount = (int)(sizeof(kPlateModes) / sizeof(kPlateModes[0]));")
print(f"static constexpr double kPlateTableLamMax = {LAM_MAX:g};")
print(f"static constexpr double kPlateWkbDelta0 = {d0:.9f};")
print(f"static constexpr double kPlateWkbDelta1 = {d1:.9f};")
print(f"static constexpr double kPlateWkbDelta2 = {d2:.9f};")
print()
print("#endif /* PlateModesTable_hpp */")
